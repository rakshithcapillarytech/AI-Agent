"""`kb review`: collect every ⚠️ callout into knowledge_base/REVIEW.md, the SME review checklist.

    uv run python -m app.kb.review

The file is regenerated from the knowledge files, so resolve an item by fixing the knowledge
file (remove or rewrite the callout) and re-running this command; don't edit REVIEW.md by hand.
"""

import sys
from dataclasses import dataclass
from pathlib import Path

from app.config import get_settings

SKIP_DIRS = {"_template", "source", "inbox"}
SKIP_FILES = {"README.md", "CHANGELOG.md", "REVIEW.md"}
KINDS = ("Source doc correction", "Gap", "Other")


@dataclass
class Callout:
    file: str
    line: int
    kind: str
    text: str


def _kind(text: str) -> str:
    if "Source doc correction" in text:
        return "Source doc correction"
    if "Gap" in text:
        return "Gap"
    return "Other"


def collect(kb_dir: Path) -> list[Callout]:
    callouts = []
    for path in sorted(kb_dir.rglob("*.md")):
        rel = path.relative_to(kb_dir)
        if rel.parts[0] in SKIP_DIRS or rel.name in SKIP_FILES:
            continue
        lines = path.read_text(encoding="utf-8").splitlines()
        for i, line in enumerate(lines):
            if "⚠️" not in line:
                continue
            block = [line.strip().lstrip(">").strip()]
            # A blockquote callout continues on following "> " lines.
            if line.lstrip().startswith(">"):
                j = i + 1
                while j < len(lines) and lines[j].lstrip().startswith(">"):
                    block.append(lines[j].strip().lstrip(">").strip())
                    j += 1
            text = " ".join(part for part in block if part)
            callouts.append(Callout(str(rel), i + 1, _kind(text), text))
    return callouts


def render(callouts: list[Callout]) -> str:
    out = [
        "# Knowledge base review checklist",
        "",
        "Generated by `uv run python -m app.kb.review`. Don't edit by hand: resolve an item in its "
        "knowledge file, then regenerate.",
        "",
        "| File | " + " | ".join(KINDS) + " |",
        "|---|" + "---|" * len(KINDS),
    ]
    files = sorted({c.file for c in callouts})
    for f in files:
        counts = [sum(1 for c in callouts if c.file == f and c.kind == k) for k in KINDS]
        out.append(f"| `{f}` | " + " | ".join(str(n) for n in counts) + " |")
    totals = [sum(1 for c in callouts if c.kind == k) for k in KINDS]
    out.append("| **Total** | " + " | ".join(f"**{n}**" for n in totals) + " |")

    for f in files:
        out += ["", f"## `{f}`"]
        for kind in KINDS:
            items = [c for c in callouts if c.file == f and c.kind == kind]
            if not items:
                continue
            out += ["", f"### {kind}s ({len(items)})", ""]
            out += [f"- [ ] L{c.line}: {c.text}" for c in items]
    return "\n".join(out) + "\n"


def main() -> int:
    kb_dir = get_settings().knowledge_base_dir
    callouts = collect(kb_dir)
    (kb_dir / "REVIEW.md").write_text(render(callouts), encoding="utf-8")
    totals = ", ".join(f"{sum(1 for c in callouts if c.kind == k)} {k.lower()}s" for k in KINDS)
    print(f"Wrote knowledge_base/REVIEW.md: {len(callouts)} items ({totals})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
