/**
 * Copy text, returning whether it worked. The async Clipboard API can be refused (unfocused
 * document, embedded frames, locked-down browsers), so fall back to a hidden textarea with
 * execCommand("copy"). Callers should show the text for manual copying when this returns false.
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // fall through to the legacy path
  }
  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "fixed";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.select();
  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    textarea.remove();
  }
}
